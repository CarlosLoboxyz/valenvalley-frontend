// Generates static/THIRD_PARTY_NOTICES.txt from package-lock.json + node_modules.
//
// Runs automatically before `npm run build` (see "prebuild" in package.json), so the
// notices always match the installed dependency set and are served with the app at
// /THIRD_PARTY_NOTICES.txt.
//
// Scope: every package installed in node_modules (runtime AND build tooling). Several
// "dev" dependencies (svelte, @sveltejs/kit, ...) are bundled into the client/server
// output, so filtering by the lockfile `dev` flag would under-report. Packages that are
// listed in the lockfile but not installed on this platform (optional native binaries)
// are skipped.
//
// Usage: node scripts/generate-notices.mjs [--check]
//   --check  exit 1 if any installed package uses a license outside the allow-list.

import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
const OUT = join(root, 'static', 'THIRD_PARTY_NOTICES.txt');

// Licenses acceptable for closed-source commercial distribution.
const ALLOWED = new Set([
	'MIT',
	'ISC',
	'BSD-2-Clause',
	'BSD-3-Clause',
	'Apache-2.0',
	'0BSD',
	'BlueOak-1.0.0',
	'CC0-1.0',
	'Python-2.0',
	'MPL-2.0', // weak copyleft: fine while the files are used unmodified
	'Unlicense'
]);

const LICENSE_FILE = /^(licen[sc]e|copying|notice)(\.|$|-)/i;

function licenseOf(meta, entry) {
	const l = meta.license ?? entry.license;
	if (typeof l === 'string') return l;
	if (l && typeof l === 'object' && l.type) return l.type;
	if (Array.isArray(meta.licenses)) return meta.licenses.map((x) => x.type).join(' OR ');
	return 'UNKNOWN';
}

function licenseTexts(dir) {
	let names;
	try {
		names = readdirSync(dir);
	} catch {
		return [];
	}
	return names
		.filter((n) => LICENSE_FILE.test(n))
		.sort()
		.map((n) => readFileSync(join(dir, n), 'utf8').trim())
		.filter(Boolean);
}

const pkgs = [];
for (const [path, entry] of Object.entries(lock.packages)) {
	if (!path.includes('node_modules/')) continue; // skip the root project
	const dir = join(root, path);
	const pj = join(dir, 'package.json');
	if (!existsSync(pj)) continue; // optional dependency not installed here
	const meta = JSON.parse(readFileSync(pj, 'utf8'));
	pkgs.push({
		name: meta.name ?? path.split('node_modules/').pop(),
		version: meta.version ?? entry.version,
		license: licenseOf(meta, entry),
		repo: typeof meta.repository === 'string' ? meta.repository : (meta.repository?.url ?? ''),
		texts: licenseTexts(dir)
	});
}
pkgs.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const bad = pkgs.filter((p) => !p.license.split(/[()\s]+(?:OR|AND)[()\s]+|[()]/).every((id) => !id.trim() || ALLOWED.has(id.trim())));
if (process.argv.includes('--check')) {
	if (bad.length) {
		console.error('Packages with licenses outside the allow-list:');
		for (const p of bad) console.error(`  ${p.name}@${p.version}: ${p.license}`);
		process.exit(1);
	}
	console.log(`OK: ${pkgs.length} packages, all licenses in the allow-list.`);
	process.exit(0);
}

// De-duplicate identical license texts (e.g. hundreds of identical MIT files).
const texts = new Map();
const keyOf = (t) => createHash('sha256').update(t.replace(/\s+/g, ' ')).digest('hex').slice(0, 12);
for (const p of pkgs) {
	p.refs = p.texts.map((t) => {
		const k = keyOf(t);
		if (!texts.has(k)) texts.set(k, { text: t, users: [] });
		texts.get(k).users.push(`${p.name}@${p.version}`);
		return k;
	});
}

const lines = [];
lines.push('THIRD-PARTY SOFTWARE NOTICES', '');
lines.push('This product includes third-party open source software, listed below with');
lines.push('its license. Generated by scripts/generate-notices.mjs; do not edit by hand.', '');
lines.push(`Packages: ${pkgs.length}`, '', '='.repeat(78), 'PACKAGES', '='.repeat(78), '');
for (const p of pkgs) {
	lines.push(`${p.name}@${p.version}`);
	lines.push(`  License: ${p.license}`);
	if (p.repo) lines.push(`  Source:  ${p.repo.replace(/^git\+/, '')}`);
	if (p.refs.length) lines.push(`  Text:    ${[...new Set(p.refs)].map((k) => `[${k}]`).join(' ')}`);
	lines.push('');
}
lines.push('='.repeat(78), 'LICENSE TEXTS', '='.repeat(78), '');
for (const [k, { text, users }] of texts) {
	lines.push(`[${k}] used by ${users.length} package(s), e.g. ${users.slice(0, 3).join(', ')}`);
	lines.push('-'.repeat(78), text, '');
}

writeFileSync(OUT, lines.join('\n'));
console.log(`Wrote ${OUT} (${pkgs.length} packages, ${texts.size} distinct license texts).`);
if (bad.length) console.warn(`WARNING: ${bad.length} package(s) outside the allow-list; run with --check.`);
